def activation(name):
    return {{"relu": nn.ReLU, "gelu": nn.GELU, "silu": nn.SiLU,
            "tanh": nn.Tanh, "none": nn.Identity}}[name]()


class ChannelLayerNorm(nn.Module):
    """Normalize channels independently at every spatial location, or a vector."""
    def __init__(self, channels, eps=1e-6):
        super().__init__()
        self.norm = nn.LayerNorm(channels, eps=eps)

    def forward(self, x):
        if x.ndim == 4:
            return self.norm(x.permute(0, 2, 3, 1)).permute(0, 3, 1, 2)
        if x.ndim == 5:
            return self.norm(x.permute(0, 1, 3, 4, 2)).permute(0, 1, 4, 2, 3)
        return self.norm(x)


class ConvNeXtBlock(nn.Module):
    """Depthwise convolution -> channel MLP -> layer scale -> residual sum."""
    def __init__(self, channels, kernel=7, expansion=4, layer_scale=1e-6, eps=1e-6, drop_path=0):
        super().__init__()
        self.dwconv = nn.Conv2d(channels, channels, kernel, padding=kernel // 2, groups=channels)
        self.norm = nn.LayerNorm(channels, eps=eps)
        self.pwconv1 = nn.Linear(channels, channels * expansion)
        self.act = nn.GELU()
        self.pwconv2 = nn.Linear(channels * expansion, channels)
        self.gamma = nn.Parameter(torch.full((channels,), float(layer_scale))) if layer_scale > 0 else None
        self.drop_probability = drop_path

    def forward(self, x):
        branch = self.dwconv(x).permute(0, 2, 3, 1)
        branch = self.pwconv2(self.act(self.pwconv1(self.norm(branch))))
        if self.gamma is not None:
            branch = branch * self.gamma
        branch = branch.permute(0, 3, 1, 2)
        if self.training and self.drop_probability > 0:
            keep = 1 - self.drop_probability
            mask = (torch.rand((x.shape[0], 1, 1, 1), device=x.device, dtype=x.dtype) < keep).to(x.dtype)
            branch = branch * mask / keep
        return x + branch


class GlobalAveragePool(nn.Module):
    def forward(self, x):
        return x.mean(dim=(-2, -1))


